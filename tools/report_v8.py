#!/usr/bin/env python3
"""Build the v8 results report: docs/results_v8.md (every number used in the documents) and the figures in docs/figures/.
Usage: python tools/report_v8.py            (reads results/v8_runs.jsonl)
Nuclear capacity is always large reactors + small modular reactors."""
import json, os, re, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'tools'))
from value_curve import fixN, CASES

R = {}
for l in open(os.path.join(ROOT, 'results', 'v8_runs.jsonl')):
    try: j = json.loads(l); R[j['tag']] = j
    except Exception: pass

def nuc(t):
    u = R[t]['res']['units']; gw = sum((u[k].get('GW') or 0) for k in ('NUC', 'SMR') if k in u); twh = sum((u[k].get('TWh') or 0) for k in ('NUC', 'SMR') if k in u)
    return gw, twh / R[t]['res']['demand_TWh'] * 100, (u.get('SMR', {}).get('GW') or 0)
def cost(t): return R[t]['res']['cost_new']
E = 356.6   # TWh: demand not met by existing hydro (denominator of the cost)

def curve(cs, rate, infix=''):
    """{N: cost} from the fixed-N runs, and the fixN at which they were run."""
    c = {}; f0 = None
    for t, j in R.items():
        m = re.match(rf'v8_{cs}_{rate}_{infix}N(\d+)_h3$', t)
        if m: c[int(m.group(1))] = j['res']['cost_new']; f0 = j['info'].get('NUC_capex_yr_kW', f0) if int(m.group(1)) > 0 else f0
    if infix and f'v8_{cs}_{rate}_N00_h3' in R: c[0] = cost(f'v8_{cs}_{rate}_N00_h3')
    return dict(sorted(c.items())), f0

def marginal(c, f0):
    Ns = list(c); return [(a, b, f0 - (c[b] - c[a]) * E / (b - a)) for a, b in zip(Ns, Ns[1:])]

def read_case(c, f0, fx):
    cc = {N: c[N] + (fx - f0) * N / E for N in c}; nb = min(cc, key=cc.get); near = [N for N in cc if cc[N] <= cc[nb] * 1.01]
    return nb, cc[nb], cc[0] - cc[nb], min(near), max(near)

out = []; W = out.append
W("# v8 results (3-hour step, four weather years 2016-2019)\n")
W("Generated by `tools/report_v8.py` from `results/v8_runs.jsonl`. Costs in EUR per MWh of demand not met by existing hydropower (356.6 TWh). "
  "Nuclear = large reactors + small modular reactors. PI = first-plant costs for technologies without commercial plants; OB = target costs. "
  "Saving = cost of the system without any nuclear minus cost of the system with nuclear.\n")

W("## 1. Central results (free optimum)\n")
W("| Case | Rate | Nuclear GW | of which SMR | Share of demand % | Cost with nuclear | Cost without | Saving EUR/MWh | Saving bn EUR/yr |\n|---|---|---|---|---|---|---|---|---|")
for cs in ('PI', 'OB'):
    for rt in ('r5', 'r7'):
        a, b = f'v8_{cs}_{rt}_opt_h3', f'v8_{cs}_{rt}_N00_h3'
        if a in R and b in R:
            g, sh, s = nuc(a); W(f"| {cs} | {rt[1]}% | {g:.1f} | {s:.1f} | {sh:.1f} | {cost(a):.2f} | {cost(b):.2f} | {cost(b) - cost(a):.2f} | {(cost(b) - cost(a)) * E / 1000:.1f} |")

W("\n## 2. Value curve of nuclear\n")
W("Marginal value of a block of nuclear capacity = annual fixed cost (EUR/kW-yr) at which the system is indifferent between having the block or not. "
  "It does not depend on the cost assumed for nuclear. For OB two curves: with SMRs available at target cost (they replace large reactors) and without SMRs (value of nuclear as a whole).\n")
CUR = {}
for cs, rt, infix, lab in (('PI', 'r5', '', 'PI 5%'), ('OB', 'r5', '', 'OB 5%, SMR available'), ('OB', 'r5', 'nosmr_', 'OB 5%, no SMR'),
                           ('PI', 'r7', '', 'PI 7%'), ('OB', 'r7', '', 'OB 7%, SMR available'), ('OB', 'r7', 'nosmr_', 'OB 7%, no SMR')):
    c, f0 = curve(cs, rt, infix)
    if len(c) < 3 or f0 is None: continue
    CUR[lab] = (c, f0, rt)
    W(f"\n**{lab}** (runs at fixN {f0:.1f})\n\n| N GW | Cost EUR/MWh | Marginal value of the next block EUR/kW-yr |\n|---|---|---|")
    mv = {a: v for a, b, v in marginal(c, f0)}
    for N in c: W(f"| {N} | {c[N]:.3f} | {'' if N not in mv else f'{mv[N]:.0f}'} |")

W("\n## 3. Cost cases read on the value curves\n")
W("fixN = capex x idc(r, y) x CRF(r, 60) + 27.75 x 0.9 x 8.76 + grid; O&M, availability and life as in the central case for every cost case.\n")
for lab, (c, f0, rt) in CUR.items():
    r = 0.05 if rt == 'r5' else 0.07
    W(f"\n**{lab}**\n\n| Cost case | Capex EUR/kW | Years | fixN | Best N (4 GW grid) | Cost | Saving vs none | Within 1% of minimum |\n|---|---|---|---|---|---|---|---|")
    for name, k, y in CASES:
        fx = fixN(k, r, y); nb, cb, sv, lo, hi = read_case(c, f0, fx)
        W(f"| {name} | {k:,} | {y} | {fx:.0f} | {nb} | {cb:.2f} | {sv:.2f} | {lo}-{hi} GW |")

W("\n## 4. Variants (one assumption changed, 5%, free optimum)\n")
VN = [('', 'Central'), ('exp0', 'Exports earn nothing'), ('exppar', 'Exports earn the import price (115.94)'), ('x10', 'Net imports allowed up to 10% of demand'),
      ('xfree', 'Net exports allowed'), ('vreweek', 'Critical weeks chosen by low PV+wind (v7)'), ('v7imp', 'v7 import rule: 38% capacity credit, no exports'),
      ('macse', 'Batteries at the MACSE award price'), ('wx8', 'Eight weather years (2016-2019 + 1994, 1998, 2014, 2015)'),
      ('nuc7y', 'Nuclear built in 7 years'), ('nuctop', 'Nuclear at the top of the official bracket (12,700 EUR/kW)'), ('nucv7', 'Nuclear at the v7 inputs (fixN 670)')]
W("| Variant | PI nuclear GW | PI saving | OB nuclear GW | OB saving |\n|---|---|---|---|---|")
VAR = {}
for key, lab in VN:
    row = [lab]
    for cs in ('PI', 'OB'):
        a = f"v8_{cs}_r5_{key + '_' if key else ''}opt_h3"; b = f"v8_{cs}_r5_{key + '_' if key else ''}N00_h3"
        if key.startswith('nuc'): b = f'v8_{cs}_r5_N00_h3'
        if a in R:
            g = nuc(a)[0]; sv = cost(b) - cost(a) if b in R else None; VAR[(key, cs)] = (g, sv)
            row += [f"{g:.1f}", '' if sv is None else f"{sv:.2f}"]
        else: row += ['', '']
    W('| ' + ' | '.join(row) + ' |')

W("\n## 5. Central systems (3 h, 5%)\n")
def mix(t):
    u = R[t]['res']['units']; g = lambda p: sum((v.get('GW') or 0) for k, v in u.items() if k.startswith(p)); e = lambda k: (u.get(k, {}).get('GWh') or 0)
    return dict(pv=g('PV'), on=sum((v.get('GW') or 0) for k, v in u.items() if re.match(r'E\d', k)), off=sum((v.get('GW') or 0) for k, v in u.items() if re.match(r'O\d', k)),
                nuc=nuc(t)[0], csp=g('CSP'), batt=e('BATT'), h2=e('H2'), caes=e('CAES'), ldes=e('LDES'), imp=u.get('IMPORT', {}).get('GW') or 0,
                trade=R[t]['res'].get('import_TWh') or 0, cf=R[t]['res'].get('nuc_cf'))
W("| System | PV GW | Onshore GW | Offshore GW | Nuclear GW | CSP GW | Batteries GWh | Hydrogen store GWh | Compressed air GWh | Interconnection GW | Energy swapped TWh/yr | Nuclear load factor |\n|---|---|---|---|---|---|---|---|---|---|---|---|")
for t, lab in (('v8_PI_r5_opt_h3', 'PI with nuclear'), ('v8_PI_r5_N00_h3', 'PI without'), ('v8_OB_r5_opt_h3', 'OB with nuclear'), ('v8_OB_r5_N00_h3', 'OB without')):
    if t in R:
        m = mix(t); W(f"| {lab} | {m['pv']:.0f} | {m['on']:.1f} | {m['off']:.1f} | {m['nuc']:.1f} | {m['csp']:.1f} | {m['batt']:.0f} | {m['h2']:.0f} | {m['caes']:.0f} | {m['imp']:.1f} | {m['trade']:.1f} | {'' if not m['cf'] else f'{m[chr(99)+chr(102)]:.3f}'} |")
W("\nCost components (EUR/MWh):\n")
for t in ('v8_PI_r5_opt_h3', 'v8_PI_r5_N00_h3', 'v8_OB_r5_opt_h3', 'v8_OB_r5_N00_h3'):
    if t in R: W(f"- `{t}`: " + ', '.join(f"{k} {v:.2f}" for k, v in R[t]['res']['comp'].items() if abs(v) > 0.05))

open(os.path.join(ROOT, 'docs', 'results_v8.md'), 'w').write('\n'.join(out) + '\n')
json.dump(dict(curves={k: dict(cost=v[0], fixN=v[1]) for k, v in CUR.items()}, variants={f"{k[0] or 'central'}|{k[1]}": v for k, v in VAR.items()}),
          open(os.path.join(ROOT, 'results', 'v8_summary.json'), 'w'), indent=1)
print('\n'.join(out[:60]))

# ---------------------------------------------------------------- figures
try:
    import matplotlib; matplotlib.use('Agg'); import matplotlib.pyplot as plt
except Exception as e:
    print('matplotlib not available, figures skipped:', e); sys.exit(0)
FD = os.path.join(ROOT, 'docs', 'figures'); os.makedirs(FD, exist_ok=True)
INK = '#1f2933'; MUT = '#6b7785'; GRID = '#e3e7ec'; BLUE = '#2a6fb0'; ORA = '#c8621a'
plt.rcParams.update({'font.size': 8.5, 'axes.edgecolor': MUT, 'axes.labelcolor': INK, 'xtick.color': MUT, 'ytick.color': MUT, 'axes.spines.top': False, 'axes.spines.right': False,
                     'font.family': 'DejaVu Sans', 'axes.linewidth': 0.6})
T = {'it': dict(x='Potenza nucleare (GW)', y='Valore del blocco successivo (€/kW all\'anno)', c5='capitale al 5%', c7='capitale al 7%', pi='Primo impianto (PI)', ob='Obiettivo (OB), senza piccoli reattori',
                obs='Obiettivo (OB), con piccoli reattori disponibili', cen='Dukovany ufficiale', top='massimo intervallo UE', vog='Vogtle', bar='Barakah', yc='Costo del sistema (€/MWh)', band='entro l\'1% dal minimo',
                var='Nucleare ottimo (GW)'),
     'en': dict(x='Nuclear capacity (GW)', y='Value of the next block (EUR/kW-yr)', c5='5% cost of capital', c7='7% cost of capital', pi='First plant (PI)', ob='Target (OB), no SMRs',
                obs='Target (OB), SMRs available', cen='Dukovany official', top='top of EC bracket', vog='Vogtle', bar='Barakah', yc='System cost (EUR/MWh)', band='within 1% of the minimum',
                var='Optimal nuclear (GW)')}
def fig_value(lang):
    t = T[lang]; fig, axs = plt.subplots(1, 2, figsize=(7.2, 3.3), sharey=True)
    for ax, rt, r, ttl in ((axs[0], 'r5', 0.05, t['c5']), (axs[1], 'r7', 0.07, t['c7'])):
        for lab, col, ls, name in ((f'PI {rt[1]}%', BLUE, '-', t['pi']), (f'OB {rt[1]}%, no SMR', ORA, '-', t['ob']), (f'OB {rt[1]}%, SMR available', ORA, ':', t['obs'])):
            if lab not in CUR: continue
            c, f0, _ = CUR[lab]; xs = []; ys = []
            for a, b, v in marginal(c, f0): xs += [a, b]; ys += [v, v]
            ax.plot(xs, ys, color=col, ls=ls, lw=1.6 if ls == '-' else 1.1, label=name)
        for name, k, y, key in (('Dukovany official, central', 10200, 9, 'cen'), ('top', 12700, 9, 'top'), ('Vogtle', 13400, 10, 'vog'), ('Barakah', 5500, 8, 'bar')):
            fx = fixN(k, r, y); ax.axhline(fx, color=INK if key == 'cen' else MUT, lw=0.9 if key == 'cen' else 0.5, ls='-' if key == 'cen' else (0, (4, 3)))
            below = key == 'top'
            ax.text(47.5, fx - 14 if below else fx + 12, f"{t[key]} {fx:,.0f}".replace(',', '.' if lang == 'it' else ','), ha='right', va='top' if below else 'bottom', fontsize=6.8,
                    color=INK if key == 'cen' else MUT, bbox=dict(fc='white', ec='none', pad=0.4, alpha=0.85))
        ax.set_title(ttl, fontsize=8.5, color=INK, loc='left'); ax.set_xlim(0, 48); ax.set_ylim(0, 1700); ax.set_xlabel(t['x']); ax.grid(axis='y', color=GRID, lw=0.5); ax.set_axisbelow(True)
    axs[0].set_ylabel(t['y']); axs[0].legend(frameon=False, fontsize=6.8, loc='lower left')
    fig.tight_layout(); fig.savefig(os.path.join(FD, f'fig_value_{lang}.png'), dpi=220); fig.savefig(os.path.join(FD, f'fig_value_{lang}.pdf')); plt.close(fig)
def fig_cost(lang):
    t = T[lang]; fig, ax = plt.subplots(figsize=(4.6, 3.2))
    for lab, col, name in (('PI 5%', BLUE, t['pi']), ('OB 5%, no SMR', ORA, t['ob'])):
        if lab not in CUR: continue
        c, f0, _ = CUR[lab]; xs = [N for N in c if N <= 40]; ys = [c[N] for N in xs]; m = min(ys)
        ax.plot(xs, ys, color=col, lw=1.6, marker='o', ms=3, label=name); ax.fill_between([0, 40], m, m * 1.01, color=col, alpha=0.10, lw=0)
        ax.text(40.5, m * 1.005, t['band'], fontsize=6.5, color=col, va='center')
    ax.set_xlim(0, 52); ax.set_xlabel(t['x']); ax.set_ylabel(t['yc']); ax.grid(axis='y', color=GRID, lw=0.5); ax.set_axisbelow(True); ax.legend(frameon=False, fontsize=7, loc='upper center')
    fig.tight_layout(); fig.savefig(os.path.join(FD, f'fig_cost_{lang}.png'), dpi=220); fig.savefig(os.path.join(FD, f'fig_cost_{lang}.pdf')); plt.close(fig)
for lang in ('it', 'en'): fig_value(lang); fig_cost(lang)
print('figures written to', FD)
